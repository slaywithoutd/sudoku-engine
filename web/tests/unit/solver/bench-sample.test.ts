/**
 * Sampling harness and trainer (plan T14).
 *
 * The validation tests run in the normal suite. Sampling and training are
 * opt-in and slow:
 *   SAMPLES=build CORPUS_PART=<part.json> CORPUS_SHARD=i/n CORPUS_LIMIT=<cases> CORPUS_OUT=<dir>
 *     vitest run bench-sample
 * writes `<dir>/samples/<part>-<i>.json`; then
 *   SAMPLES=train CORPUS_OUT=<dir> vitest run bench-sample
 * fits every family over `<dir>/samples/*.json` and writes
 * src/solver/scheduling/model-1.ts plus <dir>/training-report.json.
 */
import { describe, expect, test } from "vitest";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import type { Corpus, CorpusEntry } from "../../solver/bench/corpus-schema";
import {
  sampleCase,
  SAMPLER_VERSION,
  DEFAULT_CAP,
  type StateSample,
} from "../../solver/bench/sample";
import {
  MIN_POSITIVES,
  TRAINER_VERSION,
  ridgeFit,
  train,
  samplesHash,
} from "../../solver/bench/train";
import { BOARD_FEATURE_NAMES } from "../../../src/solver/scheduling/features-board";
import { TechniqueEstimator, validateModel } from "../../../src/solver/scheduling/estimator";
import { MODEL_1 } from "../../../src/solver/scheduling/model-1";

const bench = fileURLToPath(new URL("../../solver/bench/", import.meta.url));
const modelPath = fileURLToPath(
  new URL("../../../src/solver/scheduling/model-1.ts", import.meta.url),
);
const mode = process.env.SAMPLES;

function trainerHash(): string {
  return createHash("sha256")
    .update(readFileSync(bench + "train.ts", "utf8").replace(/\r\n/g, "\n"))
    .update(readFileSync(bench + "sample.ts", "utf8").replace(/\r\n/g, "\n"))
    .digest("hex")
    .slice(0, 16);
}

describe.skipIf(mode !== "build")("sample build", () => {
  test(
    "samples every case of one corpus part",
    () => {
      const part = process.env.CORPUS_PART!;
      const out = `${process.env.CORPUS_OUT ?? bench}/samples/`;
      mkdirSync(out, { recursive: true });
      const [shard, shards] = (process.env.CORPUS_SHARD ?? "0/1").split("/").map(Number);
      const entries = (JSON.parse(readFileSync(part, "utf8")) as CorpusEntry[])
        .filter((_, index) => index % shards === shard)
        .slice(0, Number(process.env.CORPUS_LIMIT ?? Infinity));
      const samples: StateSample[] = [];
      for (const entry of entries) {
        samples.push(...sampleCase(entry));
        writeFileSync(`${out}${basename(part, ".json")}-${shard}.json`, JSON.stringify(samples));
      }
      expect(samples.length).toBeGreaterThan(0);
    },
    24 * 3600_000,
  );
});

describe.skipIf(mode !== "train")("train", () => {
  test("fits model-1 from every sample part", () => {
    const out = process.env.CORPUS_OUT ?? bench;
    const corpus = JSON.parse(readFileSync(bench + "corpus.json", "utf8")) as Corpus;
    const samples = readdirSync(`${out}/samples/`)
      .filter((name) => name.endsWith(".json"))
      .sort()
      .flatMap(
        (name) => JSON.parse(readFileSync(`${out}/samples/${name}`, "utf8")) as StateSample[],
      );
    const report = train(samples, {
      policyId: "explain-fair@2",
      corpusHash: corpus.corpusHash,
      trainerHash: trainerHash(),
    });
    const header = `/**
 * Generated by the T14 trainer (tests/solver/bench/train.ts); do not edit.
 * ${SAMPLER_VERSION} cap ${DEFAULT_CAP}, ${TRAINER_VERSION}, ${report.samples} calibration states,
 * samples ${report.samplesHash.slice(0, 16)}. Fitted: ${report.fitted.join(", ") || "none"}.
 * On constants (< ${MIN_POSITIVES} positives): ${report.refused.map((r) => `${r.id} (${r.positives})`).join(", ") || "none"}.
 */
import type { EstimatorModel } from "./estimator";

export const MODEL_1: EstimatorModel = ${JSON.stringify(report.model, null, 2)};
`;
    writeFileSync(modelPath, header);
    writeFileSync(`${out}/training-report.json`, JSON.stringify(report, null, 1));
    expect(validateModel(report.model)).toEqual([]);
  });
});

describe.skipIf(mode !== undefined)("sampling harness and trainer (T14)", () => {
  test("the sampler is deterministic and records quiescent states only", () => {
    const corpus = JSON.parse(readFileSync(bench + "corpus.json", "utf8")) as Corpus;
    const entry = corpus.calibration.find((candidate) => candidate.family === "classic")!;
    const first = sampleCase(entry, 512);
    const second = sampleCase(entry, 512);
    expect(samplesHash(second)).toBe(samplesHash(first));
    expect(first.length).toBeGreaterThan(0);
    for (const sample of first) {
      expect(sample.chosen.startsWith("rule-")).toBe(false);
      expect(sample.features).toHaveLength(BOARD_FEATURE_NAMES.length);
      for (const [hit, work, utility] of Object.values(sample.techniques)) {
        expect(work).toBeGreaterThanOrEqual(1);
        expect(work).toBeLessThanOrEqual(512);
        // A proof-only (facts) proposal checks with zero utility.
        if (hit === 0) expect(utility).toBe(0);
        else expect(utility).toBeGreaterThanOrEqual(0);
      }
    }
  }, 600_000);

  test("ridge fit recovers a planted linear law", () => {
    const rows = Array.from({ length: 400 }, (_, i) => [1, i % 7, (i * 3) % 11, (i * 5) % 13]);
    const targets = rows.map(([, a, b, c]) => 5 + 2 * a - 3 * b + c);
    const fit = ridgeFit(rows, targets, 1e-6);
    expect(fit.map((w) => Math.round(w * 1000) / 1000)).toEqual([5, 2, -3, 1]);
  });

  test("the trainer refuses families below the positive threshold and bounds every value", () => {
    const features = BOARD_FEATURE_NAMES.map((_, i) => i);
    const samples: StateSample[] = Array.from({ length: 300 }, (_, state) => ({
      case: "synthetic",
      partition: state % 3 === 0 ? "held-out" : "calibration",
      family: "classic",
      state,
      features,
      techniques: {
        "rich@1": [1, 100 + state, 20],
        "rare@1": [state % 50 === 0 ? 1 : 0, 2048, state % 50 === 0 ? 3 : 0],
      },
      chosen: "rich@1",
    }));
    const report = train(samples, {
      policyId: "explain-fair@2",
      corpusHash: "c",
      trainerHash: "t",
    });
    expect(report.fitted).toEqual(["rich@1"]);
    expect(report.refused.map((r) => r.id)).toEqual(["rare@1"]);
    expect(report.samples).toBe(200);
    expect(validateModel(report.model)).toEqual([]);
    expect(() => new TechniqueEstimator(report.model)).not.toThrow();
    expect(report.model.families["rich@1"]!.gain).toBe(20);
    expect(report.model.families["rich@1"]!.hit.bias).toBeGreaterThan(0);
  });

  test("model-1 is well formed and carries its identity", () => {
    expect(validateModel(MODEL_1)).toEqual([]);
    expect(MODEL_1.id).toBe("explain-fair@2");
    expect(MODEL_1.corpusHash.length).toBeGreaterThan(0);
    expect(MODEL_1.trainerHash).toBe(trainerHash());
    const corpus = JSON.parse(readFileSync(bench + "corpus.json", "utf8")) as Corpus;
    expect(MODEL_1.corpusHash).toBe(corpus.corpusHash);
  });
});
